"""Assemble a self-contained hand-off bundle for an exported SSM.

Produces a folder a *separate* project can consume with numpy + scipy alone: the model, a
generated standalone loader, the cohort manifests, and the briefing. Nothing in the bundle
imports this package.

The loader is generated by :mod:`scripts.make_standalone_loader` and then **verified against
the package's own implementation** on this very model -- same weights, same pose, same surface
distance -- so a bundle is never shipped on the assumption that the lifted code still matches.

    python scripts/make_ssm_bundle.py --model thyroid_ssm_output_excl_mm \\
        --briefing thyroid_ssm_briefing_mm_for_3dus.txt --out thyroid_ssm_mm_export
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
# Manifests worth shipping if the model folder has them; absent ones are skipped, not an error.
MANIFESTS = ["cohort.csv", "eigenvalues.csv", "evaluation.csv", "summary.json",
             "heldout.txt", "excluded.txt"]


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--model", type=Path, required=True,
                   help="a build output folder (containing model.npz) or the .npz itself")
    p.add_argument("--out", type=Path, required=True, help="bundle folder to write")
    p.add_argument("--loader-name", default="ssm_model",
                   help="module name for the generated standalone loader (default: ssm_model)")
    p.add_argument("--briefing", type=Path, default=None,
                   help="a briefing/README text file to copy in as BRIEFING.txt")
    return p.parse_args()


def verify_standalone(loader: Path, model_npz: Path) -> None:
    """Fit the same target with the generated loader and the package; require identical results."""
    sys.path.insert(0, str(loader.parent))
    try:
        standalone = __import__(loader.stem)
    finally:
        sys.path.pop(0)
    from shape_modeling.analysis.export import load_model as pkg_load

    a, b = standalone.load_model(model_npz), pkg_load(model_npz)
    assert a.units == b.units, f"units differ: {a.units} vs {b.units}"

    rng = np.random.default_rng(0)
    k = min(8, b.n_modes)
    for _ in range(3):
        weights = rng.normal(scale=0.8, size=k)
        q, _ = np.linalg.qr(rng.normal(size=(3, 3)))
        q *= np.sign(np.linalg.det(q))  # a proper rotation
        target = b.instance(weights, pose=(1.0, q, rng.normal(scale=20.0, size=3)))
        fa = a.fit_surface(target, n_modes=k, n_restarts=2)
        fb = b.fit_surface(target, n_modes=k, n_restarts=2)
        np.testing.assert_allclose(fa.weights, fb.weights, atol=0, rtol=0)
        np.testing.assert_allclose(fa.points, fb.points, atol=0, rtol=0)
        assert fa.scale == fb.scale and fa.mean_distance == fb.mean_distance
    print(f"verified: {loader.name} reproduces the package fit exactly ({k} modes, 3 targets)")


def main() -> None:
    args = parse_args()
    src = args.model
    model_npz = src if src.suffix == ".npz" else src / "model.npz"
    if not model_npz.exists():
        raise SystemExit(f"no model at {model_npz}")
    out = args.out
    out.mkdir(parents=True, exist_ok=True)

    shutil.copyfile(model_npz, out / "model.npz")
    copied = ["model.npz"]
    if model_npz.parent != src or src.is_dir():
        for name in MANIFESTS:
            if (src / name).exists():
                shutil.copyfile(src / name, out / name)
                copied.append(name)

    loader = out / f"{args.loader_name}.py"
    subprocess.run([sys.executable, str(ROOT / "scripts" / "make_standalone_loader.py"),
                    str(loader)], check=True)
    copied.append(loader.name)
    verify_standalone(loader, out / "model.npz")

    pycache = out / "__pycache__"  # left behind by verify_standalone's import
    if pycache.exists():
        shutil.rmtree(pycache)

    if args.briefing:
        shutil.copyfile(args.briefing, out / "BRIEFING.txt")
        copied.append("BRIEFING.txt")

    total = sum(f.stat().st_size for f in out.iterdir() if f.is_file())
    print(f"\nbundle written to {out}/ ({total / 1e6:.1f} MB)")
    for name in copied:
        print(f"  {name}")


if __name__ == "__main__":
    main()
